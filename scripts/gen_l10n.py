def escape_strings_value(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "")
    )


def write_strings(path: Path, mapping: dict[str, str]) -> None:
    lines = [
        "/* Localizable.strings — generated by scripts/gen_l10n.py; do not edit by hand (regenerate). */",
        "",
    ]
    for k in sorted(mapping.keys()):
        lines.append(f'"{escape_strings_value(k)}" = "{escape_strings_value(mapping[k])}";')
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    for lang in LANGS:
        over = OVERRIDES.get(lang, {})
        merged = {**EN, **over}
        # iOS/macOS uses zh-Hans.lproj folder name
        folder = lang
        out = ROOT / f"{folder}.lproj" / "Localizable.strings"
        write_strings(out, merged)
        print("wrote", out, "keys", len(merged))


if __name__ == "__main__":
    main()
